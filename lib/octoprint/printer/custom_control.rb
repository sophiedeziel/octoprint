# typed: true
# frozen_string_literal: true

module Octoprint
  class Printer
    # A custom control as configured in OctoPrint's +config.yaml+.
    #
    # There are two kinds of custom controls: containers, which group other controls in +children+,
    # and controls, which send a +command+, +commands+ or +script+ to the printer and/or display
    # output matched by +regex+ and rendered with +template+.
    #
    # @example
    #   fan = Octoprint::Printer::Command.custom_controls.first
    #   fan.container?                    # => true
    #   fan.children.first.command        # => "M106 S%(speed)s"
    #   fan.children.first.input.first    # => #<Octoprint::Printer::CustomControl::Input ...>
    #
    # @see https://docs.octoprint.org/en/master/features/custom_controls.html
    class CustomControl
      extend T::Sig
      include AutoInitializable
      include Deserializable

      # @!attribute [r] name
      #   @return [String, nil] The name of the control or container
      auto_attr :name, type: String

      # @!attribute [r] type
      #   @return [String, nil] The control type, if set in the configuration
      auto_attr :type, type: String

      # @!attribute [r] children
      #   @return [Array<Printer::CustomControl>, nil] The controls contained in a container
      auto_attr :children, type: CustomControl, array: true

      # @!attribute [r] layout
      #   @return [String, nil] The container's layout: +vertical+, +horizontal+ or +horizontal_grid+
      auto_attr :layout, type: String

      # @!attribute [r] collapsed
      #   @return [Boolean, nil] Whether the container is collapsed by default
      auto_attr :collapsed, type: Types::Boolean

      # @!attribute [r] width
      #   @return [String, Integer, nil] The control's width in a grid layout
      auto_attr :width, type: T.untyped

      # @!attribute [r] offset
      #   @return [String, Integer, nil] The control's offset in a grid layout
      auto_attr :offset, type: T.untyped

      # @!attribute [r] command
      #   @return [String, nil] A single GCODE command sent by the control
      auto_attr :command, type: String

      # @!attribute [r] commands
      #   @return [Array<String>, nil] GCODE commands sent by the control
      auto_attr :commands, type: String, array: true

      # @!attribute [r] script
      #   @return [String, nil] The name of a GCODE script sent by the control
      auto_attr :script, type: String

      # @!attribute [r] javascript
      #   @return [String, nil] A JavaScript snippet executed when the control is clicked
      auto_attr :javascript, type: String

      # @!attribute [r] additional_classes
      #   @return [String, nil] Additional CSS classes applied to the control's button
      auto_attr :additional_classes, type: String

      # @!attribute [r] enabled
      #   @return [String, nil] A JavaScript snippet determining whether the control is enabled
      auto_attr :enabled, type: String

      # @!attribute [r] input
      #   @return [Array<Printer::CustomControl::Input>, nil] Input parameters of the control
      auto_attr :input, type: Input, array: true

      # @!attribute [r] regex
      #   @return [String, nil] A regular expression matched against lines received from the printer
      auto_attr :regex, type: String

      # @!attribute [r] template
      #   @return [String, nil] A template used to render the +regex+ match
      auto_attr :template, type: String

      # @!attribute [r] key
      #   @return [String, nil] Identifier generated by OctoPrint for controls using +regex+
      auto_attr :key, type: String

      # @!attribute [r] template_key
      #   @return [String, nil] Identifier generated by OctoPrint for the control's +template+
      auto_attr :template_key, type: String

      # @!attribute [r] confirm
      #   @return [String, nil] A confirmation text displayed before sending the control's commands
      auto_attr :confirm, type: String

      # @!attribute [r] extra
      #   @return [Hash, nil] Any additional fields returned by the API
      auto_attr :extra, type: Hash

      auto_initialize!

      deserialize_config do
        array :children, CustomControl
        array :input, Input
      end

      # Whether this is a container grouping other controls.
      #
      # @return [Boolean] true if the control has children
      sig { returns(T::Boolean) }
      def container?
        !children.nil?
      end
    end
  end
end
